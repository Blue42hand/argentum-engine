package com.wingedsheep.mtg.sets.definitions.pip.cards

import com.wingedsheep.sdk.core.Color
import com.wingedsheep.sdk.core.Subtype
import com.wingedsheep.sdk.dsl.Costs
import com.wingedsheep.sdk.dsl.Effects
import com.wingedsheep.sdk.dsl.card
import com.wingedsheep.sdk.model.Rarity
import com.wingedsheep.sdk.scripting.GameObjectFilter
import com.wingedsheep.sdk.scripting.GrantWard
import com.wingedsheep.sdk.scripting.TimingRule
import com.wingedsheep.sdk.scripting.effects.ManaRestriction
import com.wingedsheep.sdk.scripting.effects.WardCost
import com.wingedsheep.sdk.scripting.filters.unified.GroupFilter
import com.wingedsheep.sdk.scripting.filters.unified.TargetFilter

/**
 * Codsworth, Handy Helper — Fallout #14
 * {2}{W} · Legendary Artifact Creature — Robot · 2/3
 *
 * Commanders you control have ward {2}.
 * {T}: Add {W}{W}. Spend this mana only to cast Aura and/or Equipment spells.
 * {T}: Attach target Aura or Equipment you control to target creature you control. Activate only
 * as a sorcery.
 *
 * - "Commanders you control" is a [GrantWard] over permanents carrying the commander designation
 *   (`commander()`, CR 903.3) — Codsworth itself included when it is your commander.
 * - The mana is [ManaRestriction.SubtypeSpellsOnly] over Aura and Equipment: it pays for casting
 *   those spells only, never for equip or other activated abilities (ruling).
 * - The attach ability targets both objects; [Effects.AttachTargetEquipmentToCreature] moves the
 *   attachment regardless of its type, no-ops when either target is gone, and leaves the
 *   attachment where it is when it can't legally be attached or is already on that creature
 *   (rulings, CR 701.3b).
 */
private val auraOrEquipmentYouControl =
    (GameObjectFilter.Any.withSubtype(Subtype.AURA) or GameObjectFilter.Any.withSubtype(Subtype.EQUIPMENT))
        .youControl()

val CodsworthHandyHelper = card("Codsworth, Handy Helper") {
    manaCost = "{2}{W}"
    colorIdentity = "W"
    typeLine = "Legendary Artifact Creature — Robot"
    power = 2
    toughness = 3
    oracleText = "Commanders you control have ward {2}.\n" +
        "{T}: Add {W}{W}. Spend this mana only to cast Aura and/or Equipment spells.\n" +
        "{T}: Attach target Aura or Equipment you control to target creature you control. " +
        "Activate only as a sorcery."

    staticAbility {
        ability = GrantWard(
            cost = WardCost.Mana("{2}"),
            filter = GroupFilter(GameObjectFilter.Permanent.commander().youControl())
        )
    }

    activatedAbility {
        cost = Costs.Tap
        effect = Effects.AddMana(
            Color.WHITE,
            2,
            restriction = ManaRestriction.SubtypeSpellsOnly(setOf(Subtype.AURA.value, Subtype.EQUIPMENT.value))
        )
        manaAbility = true
        timing = TimingRule.ManaAbility
    }

    activatedAbility {
        cost = Costs.Tap
        val attachment = target(TargetFilter(auraOrEquipmentYouControl))
        val creature = target(TargetFilter.CreatureYouControl)
        effect = Effects.AttachTargetEquipmentToCreature(attachment, creature)
        timing = TimingRule.SorcerySpeed
        description = "Attach target Aura or Equipment you control to target creature you control"
    }

    metadata {
        rarity = Rarity.RARE
        collectorNumber = "14"
        artist = "Alex Konstad"
        flavorText = "\"Proud to serve!\""
        imageUri = "https://cards.scryfall.io/normal/front/b/b/bbdfbd21-61b1-4ebd-8d37-bce2a391a7e9.jpg?1783912418"
        ruling("2024-03-08", "Once a commander's ward ability has triggered, causing that commander to lose ward by removing Codsworth won't affect the ability. The appropriate player will still have to pay {2} or see their spell or ability countered.")
        ruling("2024-03-08", "You can't spend mana generated by Codsworth's second ability to activate abilities of Auras or Equipment. This includes paying equip costs.")
        ruling("2024-03-08", "The Aura or Equipment you target with Codsworth's last ability doesn't have to be attached to a creature you control when you target it. You just have to control the Aura or Equipment you're targeting as well as the creature you're targeting.")
        ruling("2024-03-08", "If either target of Codsworth's last ability is an illegal target as the ability resolves, the ability won't do anything. If both targets are illegal, the ability won't resolve. If the target Aura or Equipment is already attached to the target creature, nothing happens.")
        ruling("2024-03-08", "As Codsworth's last ability resolves, if the target Aura or Equipment can't legally be attached to the target creature (for example, because the creature has protection from enchantments or protection from artifacts), the target Aura or Equipment won't move.")
    }
}
