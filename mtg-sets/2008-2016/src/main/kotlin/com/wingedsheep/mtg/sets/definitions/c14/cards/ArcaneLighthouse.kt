        ruling("2014-11-07", "After the second ability resolves, continuous effects generated by the resolution of spells and abilities that would give hexproof or shroud to one of the affected creatures aren't created. For example, after the second ability resolves, a spell cast by an opponent that gives creatures they control hexproof wouldn't cause the creatures to have hexproof. (If that spell has additional effects, such as raising the power of the creatures, those effects will apply as normal.)")
        ruling("2014-11-07", "Continuous effects generated by static abilities (such as an Aura that grants hexproof to a creature) will not apply during the turn, but will resume applying once the turn ends.")
        ruling("2014-11-07", "The second ability applies only to creatures controlled by your opponents when it resolves. Creatures that enter the battlefield or come under an opponent's control later in the turn won't be affected.")
    }
