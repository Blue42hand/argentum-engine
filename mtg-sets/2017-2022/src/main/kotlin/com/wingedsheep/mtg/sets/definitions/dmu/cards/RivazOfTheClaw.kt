package com.wingedsheep.mtg.sets.definitions.dmu.cards

import com.wingedsheep.sdk.core.Keyword
import com.wingedsheep.sdk.core.Subtype
import com.wingedsheep.sdk.core.Zone
import com.wingedsheep.sdk.dsl.Costs
import com.wingedsheep.sdk.dsl.Effects
import com.wingedsheep.sdk.dsl.Triggers
import com.wingedsheep.sdk.dsl.card
import com.wingedsheep.sdk.dsl.grantedTriggeredAbility
import com.wingedsheep.sdk.model.Rarity
import com.wingedsheep.sdk.scripting.Duration
import com.wingedsheep.sdk.scripting.GameObjectFilter
import com.wingedsheep.sdk.scripting.MayCastFromGraveyard
import com.wingedsheep.sdk.scripting.TimingRule
import com.wingedsheep.sdk.scripting.effects.ManaRestriction
import com.wingedsheep.sdk.scripting.events.SpellCastPredicate
import com.wingedsheep.sdk.scripting.targets.EffectTarget

/**
 * Rivaz of the Claw
 * {1}{B}{R}
 * Legendary Creature — Lizard Warlock
 * 3/3
 * Menace
 * {T}: Add two mana in any combination of colors. Spend this mana only to cast Dragon creature spells.
 * Once during each of your turns, you may cast a Dragon creature spell from your graveyard.
 * Whenever you cast a Dragon creature spell from your graveyard, it gains "When this creature dies,
 * exile it."
 *
 * - The mana is Gwenna's [Effects.AddManaInAnyCombination] with The Seedcore's creature-only
 *   subtype restriction.
 * - The graveyard permission is Gisa and Geralf's once-per-your-turn [MayCastFromGraveyard].
 * - The last ability is a separate cast trigger, not the grant's entry rider: per the ruling it
 *   fires for a Dragon cast from the graveyard "for any reason", not only under Rivaz's permission.
 *   The grant lands on the permanent spell on the stack (Thief of Existence's shape) and carries
 *   onto the creature it becomes; a spell countered first never gets it.
 */
val RivazOfTheClaw = card("Rivaz of the Claw") {
    manaCost = "{1}{B}{R}"
    colorIdentity = "BR"
    typeLine = "Legendary Creature — Lizard Warlock"
    power = 3
    toughness = 3
    oracleText = "Menace\n" +
        "{T}: Add two mana in any combination of colors. Spend this mana only to cast Dragon creature spells.\n" +
        "Once during each of your turns, you may cast a Dragon creature spell from your graveyard.\n" +
        "Whenever you cast a Dragon creature spell from your graveyard, it gains \"When this creature dies, exile it.\""

    keywords(Keyword.MENACE)

    activatedAbility {
        cost = Costs.Tap
        effect = Effects.AddManaInAnyCombination(
            amount = 2,
            restriction = ManaRestriction.SubtypeSpellsOrAbilitiesOnly("Dragon", creatureOnly = true),
        )
        manaAbility = true
        timing = TimingRule.ManaAbility
    }

    staticAbility {
        ability = MayCastFromGraveyard(
            filter = GameObjectFilter.Creature.withSubtype(Subtype.DRAGON),
            duringYourTurnOnly = true,
            oncePerTurn = true,
        )
    }

    triggeredAbility {
        trigger = Triggers.you.casts(
            GameObjectFilter.Creature.withSubtype(Subtype.DRAGON),
            requires = setOf(SpellCastPredicate.CastFromZone(Zone.GRAVEYARD)),
        )
        effect = Effects.GrantTriggeredAbility(
            ability = grantedTriggeredAbility {
                trigger = Triggers.self.dies()
                effect = Effects.Move(EffectTarget.Self, Zone.EXILE, fromZone = Zone.GRAVEYARD)
                description = "When this creature dies, exile it."
            },
            target = EffectTarget.TriggeringEntity,
            duration = Duration.Permanent,
        )
        description = "Whenever you cast a Dragon creature spell from your graveyard, it gains " +
            "\"When this creature dies, exile it.\""
    }

    metadata {
        rarity = Rarity.RARE
        collectorNumber = "215"
        artist = "Joshua Raphael"
        imageUri = "https://cards.scryfall.io/normal/front/9/a/9a47573a-601e-4738-acef-16118289f939.jpg?1783921278"

        ruling("2022-09-09", "You can use mana generated by the activated ability to pay an alternative cost (such as an escape cost) or an additional cost to cast a Dragon spell. It's not limited to paying just that spell's mana cost.")
        ruling("2022-09-09", "The casting permission granted by Rivaz's third ability doesn't change when you may cast the spell from your graveyard.")
        ruling("2022-09-09", "The last ability triggers when you cast a Dragon creature spell from your graveyard for any reason. It triggers even if you didn't use mana generated by Rivaz's activated ability to pay its costs.")
        ruling("2022-09-09", "The ability that the spell gains as Rivaz's last ability resolves continues to apply to the permanent that spell becomes after the spell resolves, even if it stops being a Dragon or stops being a creature.")
        ruling("2022-09-09", "The ability that the spell gains only applies to it once it's on the battlefield. If the spell is countered before it resolves, that ability will not exile it.")
    }
}
